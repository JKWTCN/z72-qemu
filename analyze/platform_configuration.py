ALL_STATUS_WORDS = tuple(p[1] for p in COMPLETION_PAIRS)
# The final poll in each group is followed by a write to the previous status
# word, so these two completions remain pending in the synchronous model.
PENDING_STATUS_WORDS = (0x2002E300, 0x2004E300)
RESULT_WORDS = (0x2003016C, 0x2005016C)


def platform_writes(role, shared=False):
    first = expected_completion_writes(role, shared) + GROUP_WRITES
    second = tuple((a + 0x20000, SECOND_CHANNEL_VALUES.get(a + 0x20000, v))
                   for a, v in first)
    return first + second


PLATFORM_WORDS = tuple(sorted(set(dict(platform_writes('master'))) |
    set(ALL_STATUS_WORDS) | set(RESULT_WORDS)))


def platform_calls(role, shared=False):
    if role == 'master':
        return (0x4C6C, 0x5354), (0x3A8, 0x3B0, 0x3BC, 0xBDC4), 0x8D4
    if role == 'slave':
        if shared:
            return (0x4CB8, 0x53A0), (0x3C8, 0x3D0, 0x3DC, 0xBE10), 0x920
        return (0x361C, 0x3D10), (0x3EC, 0x3F4, 0x400, 0xBE10), 0x920
    raise ValueError('Unsupported firmware role')
