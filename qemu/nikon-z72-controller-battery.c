/* Synthetic battery peer for the controller battery serial interface.
 *
 * Firmware analysis recovered the startup exchanges and the field
 * arithmetic behind the authentication exchange: the controller publishes
 * the x-coordinate of a random multiple of a fixed base point, keeps the
 * same random multiple of a second fixed base point internally, and
 * accepts a reply whose result field carries the low eight bytes of the
 * field product of that internal value with the reply's own field.  The
 * arithmetic runs in GF(2^131) modulo x^131+x^8+x^3+x^2+1 with the
 * recovered X-only Montgomery ladder.
 *
 * The nonce of every authentication round is generated by a software
 * generator inside the same deterministic machine, so this peer reads it
 * from controller RAM through the controller memory root, verifies that
 * the published challenge matches, and only then answers.  Without a
 * matching challenge the peer stays silent and the original timeout and
 * failure paths run unchanged.
 */
#include "qemu/osdep.h"
#include "chardev/char.h"
#include "chardev/char-fe.h"
#include "system/address-spaces.h"
#include "system/reset.h"
#include "qemu/timer.h"
#include "qapi/error.h"
#include "nikon-z72-controller.h"

/* Fixed little-endian 131-bit constants recovered from the firmware. */
static const uint64_t base_a[3] =
    { 0x4ec4b6f5d285601f, 0x0720a61b50252fd3, 0x0000000000000006 };
static const uint64_t base_b[3] =
    { 0x3f3a3bd9c53f4ecf, 0x0fdc0f0f00862f76, 0x0000000000000000 };
static const uint64_t curve_b[3] =
    { 0xe2ed5a9b1b80055e, 0x3d078a701dcff787, 0x0000000000000000 };

/* Controller RAM addresses of the eighteen-byte nonce buffer and the
 * published challenge of the running authentication round. */
#define NONCE_ADDRESS     0x2001F446
#define PUBLISHED_ADDRESS 0x2001F458

/* An experimental identifier, unrelated to any physical battery. */
static const uint8_t battery_id[8] = "LAB00001";

typedef struct {
    uint64_t w[3];              /* bits 0..190; values stay below 2^131 */
} gf131;

static void gf_zero(gf131 *a)
{
    memset(a->w, 0, sizeof(a->w));
}

static void gf_one(gf131 *a)
{
    gf_zero(a);
    a->w[0] = 1;
}

static bool gf_is_zero(const gf131 *a)
{
    return (a->w[0] | a->w[1] | a->w[2]) == 0;
}

static bool gf_equal(const gf131 *a, const gf131 *b)
{
    return a->w[0] == b->w[0] && a->w[1] == b->w[1] && a->w[2] == b->w[2];
}

static void gf_copy(gf131 *d, const gf131 *s)
{
    memcpy(d->w, s->w, sizeof(d->w));
}

static void gf_xor(gf131 *d, const gf131 *s)
{
    d->w[0] ^= s->w[0];
    d->w[1] ^= s->w[1];
    d->w[2] ^= s->w[2];
}

static void gf_flip(gf131 *a, unsigned bit)
{
    a->w[bit / 64] ^= 1ull << (bit % 64);
}

/* Carry-less product reduced modulo x^131+x^8+x^3+x^2+1. */
static void gf_mul(gf131 *out, const gf131 *a, const gf131 *b)
{
    uint64_t p[6] = { 0 };

    for (unsigned i = 0; i < 3; i++) {
        for (unsigned bit = 0; bit < 64; bit++) {
            if (!((b->w[i] >> bit) & 1)) {
                continue;
            }
            unsigned shift = i * 64 + bit;
            for (unsigned j = 0; j < 3; j++) {
                unsigned index = (shift + j * 64) / 64;
                unsigned offset = (shift + j * 64) % 64;
                uint64_t word = a->w[j];
                p[index] ^= offset ? word << offset : word;
                if (offset) {
                    p[index + 1] ^= word >> (64 - offset);
                }
            }
        }
    }
    /* Fold every bit at or above x^131 using x^131 = x^8+x^3+x^2+1. */
    for (int bit = 5 * 64 + 63; bit >= 131; bit--) {
        unsigned limb = bit / 64, offset = bit % 64;
        if (!((p[limb] >> offset) & 1)) {
            continue;
        }
        p[limb] ^= 1ull << offset;
        unsigned low = bit - 131;
        static const unsigned taps[4] = { 0, 2, 3, 8 };
        for (unsigned t = 0; t < 4; t++) {
            unsigned site = low + taps[t];
            p[site / 64] ^= 1ull << (site % 64);
        }
    }
    out->w[0] = p[0];
    out->w[1] = p[1];
    out->w[2] = p[2] & 7;
}

static void gf_from_le(gf131 *a, const uint8_t *bytes, unsigned length)
{
    gf_zero(a);
    for (unsigned i = 0; i < length; i++) {
        for (unsigned bit = 0; bit < 8; bit++) {
            if ((bytes[i] >> bit) & 1) {
                gf_flip(a, i * 8 + bit);
            }
        }
    }
}

/* X-only differential addition: P+Q with the difference given as delta. */
static void ladder_add(gf131 *x, gf131 *z,
                       const gf131 *x1, const gf131 *z1,
                       const gf131 *x2, const gf131 *z2,
                       const gf131 *delta)
{
    gf131 t1, t2, sum, t;
    gf_mul(&t1, x1, z2);
    gf_mul(&t2, z1, x2);
    gf_copy(&sum, &t1);
    gf_xor(&sum, &t2);
    gf_mul(z, &sum, &sum);              /* (X1 Z2 + X2 Z1)^2 */
    gf_mul(x, &t1, &t2);
    gf_mul(&t, delta, z);
    gf_xor(x, &t);
}

static void ladder_double(gf131 *x, gf131 *z, const gf131 *x1, const gf131 *z1)
{
    gf131 xx, zz, scaled, sum;
    gf_mul(&xx, x1, x1);
    gf_mul(&zz, z1, z1);
    memcpy(scaled.w, curve_b, sizeof(scaled.w));
    gf_mul(&scaled, &scaled, &zz);      /* b Z^2 */
    gf_copy(&sum, &xx);
    gf_xor(&sum, &scaled);              /* X^2 + b Z^2 */
    gf_mul(x, &sum, &sum);              /* (X^2 + b Z^2)^2 */
    gf_mul(z, &xx, &zz);                /* X^2 Z^2 */
}

static void gf_invert(gf131 *out, const gf131 *a)
{
    /* a^(2^131-2); exponent bits 1..130 set, bit 0 clear. */
    static const uint64_t exponent[3] =
        { 0xfffffffffffffffeull, 0xffffffffffffffffull, 0x0000000000000007ull };
    gf131 result, base;
    gf_one(&result);
    gf_copy(&base, a);
    for (int bit = 130; bit >= 0; bit--) {
        gf_mul(&result, &result, &result);
        if ((exponent[bit / 64] >> (bit % 64)) & 1) {
            gf_mul(&result, &result, &base);
        }
    }
    gf_copy(out, &result);
}

/* X-only Montgomery ladder over the low 128 bits of the scalar. */
static bool ladder(gf131 *out, const gf131 *base, const uint8_t scalar[18])
{
    gf131 ax, az, bx, bz, nx, nz;
    gf_one(&ax);                        /* identity (1:0) */
    gf_zero(&az);
    gf_copy(&bx, base);
    gf_one(&bz);
    for (int i = 127; i >= 0; i--) {
        bool bit = (scalar[i / 8] >> (i % 8)) & 1;
        ladder_add(&nx, &nz, &ax, &az, &bx, &bz, base);
        if (bit) {
            ladder_double(&bx, &bz, &bx, &bz);
            ax = nx;
            az = nz;
        } else {
            ladder_double(&ax, &az, &ax, &az);
            bx = nx;
            bz = nz;
        }
    }
    if (gf_is_zero(&az)) {
        return false;                   /* identity: original reports failure */
    }
    gf131 inverse;
    gf_invert(&inverse, &az);
    gf_mul(out, &ax, &inverse);
    return true;
}

